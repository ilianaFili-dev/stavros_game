#!/usr/bin/env python3
"""Generate src/generated/sheets.h from the design sheets.

One struct per sheet, one constexpr row per sheet row (rows up to --milestone only).
Refuses to run unless preflight is clean for that milestone.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from preflight import MILESTONES, ROOT, load_sheets, preflight  # noqa: E402

OUT = ROOT / "src" / "generated" / "sheets.h"

CTYPE = {
    "id": "const char*", "string": "const char*", "ref": "const char*", "enum": "const char*",
    "int": "int", "number": "float", "bool": "bool", "vec3": "Vec3",
    "vec3_list": "std::initializer_list<Vec3>", "int_list": "std::initializer_list<int>",
    "string_list": "std::initializer_list<const char*>", "ref_list": "std::initializer_list<const char*>",
}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_value(col, v):
    t = col["type"]
    if v is None:
        return {"int": "0", "number": "0.0f", "bool": "false", "vec3": "Vec3{}"}.get(t, "nullptr" if "list" not in t else "{}")
    if t in ("id", "string", "ref", "enum"):
        return c_str(v)
    if t == "int":
        return str(v)
    if t == "number":
        return f"{float(v)}f"
    if t == "bool":
        return "true" if v else "false"
    if t == "vec3":
        return "Vec3{%sf, %sf, %sf}" % tuple(float(x) for x in v)
    if t == "vec3_list":
        return "{" + ", ".join(c_value({"type": "vec3"}, x) for x in v) + "}"
    if t == "int_list":
        return "{" + ", ".join(str(x) for x in v) + "}"
    return "{" + ", ".join(c_str(x) for x in v) + "}"


def struct_name(sheet):
    return "".join(p.capitalize() for p in sheet.split("_")) + "Row"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--milestone", default="M0", choices=MILESTONES)
    args = ap.parse_args()
    sheets = load_sheets()
    problems = preflight(sheets, args.milestone)
    if problems:
        print(f"preflight for {args.milestone} is not clean ({len(problems)} open cells); run tools/preflight.py", file=sys.stderr)
        sys.exit(1)
    limit = MILESTONES.index(args.milestone)
    lines = [
        "// Generated by tools/gen.py from design/sheets. Do not edit; change the sheet instead.",
        f"// Milestone: {args.milestone}",
        "#pragma once",
        "#include <initializer_list>",
        "",
        "namespace sheets {",
        "",
        "struct Vec3 { float x, y, z; };",
        "",
    ]
    for name, s in sheets.items():
        rows = [r for r in s["rows"] if MILESTONES.index(r["milestone"]) <= limit]
        cols = s["columns"]
        # list columns can't live in a constexpr aggregate array; keep scalars in the struct
        scalar = {c: col for c, col in cols.items() if "list" not in col["type"]}
        sn = struct_name(name)
        lines.append(f"// {s['description']}")
        lines.append(f"struct {sn} {{")
        for c, col in scalar.items():
            lines.append(f"    {CTYPE[col['type']]} {c};")
        lines.append("};")
        lines.append(f"inline constexpr {sn} {name}[] = {{")
        for r in rows:
            lines.append("    {" + ", ".join(c_value(col, r.get(c)) for c, col in scalar.items()) + "},")
        if not rows:
            lines.append("    {" + ", ".join(c_value(col, None) for col in scalar.values()) + "},  // placeholder: no rows in this milestone")
        lines.append("};")
        lines.append(f"inline constexpr int {name}_count = {len(rows)};")
        lines.append("")
    lines.append("}  // namespace sheets")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
